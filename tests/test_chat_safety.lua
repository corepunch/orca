package.path = "apps/chat/?.lua;" .. package.path
local Chat = require "api.chat"
local client = Chat.demo()
local before = assert(client:listMessages("alex"))
local incoming
for _, message in ipairs(before) do if message.sender_id == "alex" then incoming = message end end
assert(incoming)
local result, err = client:setUserBlocked("me", true)
assert(not result and err.code == "validation", "Self-block fails before transport")
assert(client:setUserBlocked("alex", true))
assert(assert(client:listBlocks())[1].user_id == "alex", "Blocked people are available for unblocking")
result, err = client:sendMessage("alex", "Blocked direct message")
assert(not result and err.status == 403, "Persisted blocks prevent direct sends")
result, err = client:createRoom("Another direct", { "alex" }, { kind = "direct" })
assert(not result and err.status == 403, "A fresh direct conversation cannot bypass a block")
assert(client:sendMessage("weekend", "Shared group messages remain visible"), "Blocking does not pretend to hide shared group content")
assert(client:signOut())
assert(client:signIn("demo@example.invalid", "password123"))
assert(#assert(client:listBlocks()) == 1, "Blocks survive session changes")
local report = assert(client:reportContent("alex", "harassment", "Please review", incoming.id))
assert(report.submitted and report.id, "A blocked person's visible message can still be reported")
result, err = client:reportContent("alex", "invalid", "")
assert(not result and err.code == "validation", "Unknown report reasons fail before transport")
result, err = client:reportContent("alex", "other", string.rep("x", 1001))
assert(not result and err.code == "validation", "Oversized report details are refused")
result, err = client:reportContent("alex", "other", "", "not-visible")
assert(not result and err.status == 403, "Reports cannot invent inaccessible message evidence")
assert(client:setUserBlocked("alex", false))
assert(#assert(client:listBlocks()) == 0 and client:sendMessage("alex", "Allowed again"), "Unblocking restores direct messaging")
local rules = assert(client:getRulesState())
assert(rules.version == "2026-11-08" and not rules.accepted_version)
assert(client:acceptRules())
assert(assert(client:getRulesState()).accepted_version == rules.version, "Explicit rules acceptance persists per account")
assert(client:signOut())
result, err = client:reportContent("alex", "spam", "")
assert(not result and err.code == "unauthenticated", "Reporting requires an authenticated account")
print("PASS: Chat safety client validation, persisted blocks, reports and rules")
