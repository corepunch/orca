-- Run from samples/Book: lua Tools/export_workshop_camera.lua
-- Exports camera + resolved interaction anchors; does not export scene geometry.
package.path = "Scripts/?.lua;Tools/?.lua;" .. package.path
local Projection = require "SceneProjection"
local Export = {}

local function scalar(n) return string.format("%.12g", n) end
local function vec(v) return table.concat({scalar(v[1]), scalar(v[2]), scalar(v[3])}, " ") end
local function luaVec(v) return "{" .. table.concat({scalar(v[1]), scalar(v[2]), scalar(v[3])}, ", ") .. "}" end
local function quoted(s) return string.format("%q", s) end
local function xmlEscape(s)
    return s:gsub("&", "&amp;"):gsub('"', "&quot;"):gsub("<", "&lt;"):gsub(">", "&gt;")
end

function Export.generate(spec, scene)
    assert(scene.cameras[spec.camera], "missing default export camera")
    -- Rotate Z-up source coordinates into Orca's Y-up basis without mirroring.
    local function nativePoint(point)
        if scene.up == "z" then return {point[1], point[3], -point[2]} end
        return point
    end
    local order = {}
    for name in pairs(scene.cameras) do order[#order + 1] = name end
    table.sort(order)
    local xml = {
        '<?xml version="1.0"?>',
        '<!-- Generated by Tools/export_workshop_camera.lua; regenerate after changing the blocking scene. -->',
        '<Scene Name="WorkshopCamera" Camera="#' .. xmlEscape(spec.camera) .. '">',
    }
    local lua = {
        '-- Generated by Tools/export_workshop_camera.lua; regenerate, do not edit.',
        'return {',
        '    source_path = ' .. quoted(spec.scene_path) .. ',',
        '    source_width = ' .. scalar(spec.source_width) .. ',',
        '    source_height = ' .. scalar(spec.source_height) .. ',',
        '    native_scene_path = "Book/Scenes/WorkshopCamera.xml",',
        '    default_camera = ' .. quoted(spec.camera) .. ',',
        '    cameras = {',
    }
    for _, name in ipairs(order) do
        local source = scene.cameras[name]
        local camera = {pos = nativePoint(source.pos), look = nativePoint(source.look), fov = source.fov}
        local dx, dy, dz = camera.look[1]-camera.pos[1], camera.look[2]-camera.pos[2], camera.look[3]-camera.pos[3]
        local length = math.sqrt(dx*dx + dy*dy + dz*dz)
        -- Skip degenerate/overhead references: a vertical look has no yaw convention.
        if length > 1e-8 and math.sqrt(dx*dx + dz*dz) > 1e-8 then
            -- ORCA: Rz*Ry*Rx, local -Z forward, +Y up.
            local rotation = {math.asin(dy/length)*180/math.pi, math.atan(-dx, -dz)*180/math.pi, 0}
            xml[#xml + 1] = '  <Camera Name="' .. xmlEscape(name) .. '"'
                .. ' RenderTransformTranslation="' .. vec(camera.pos) .. '"'
                .. ' RenderTransformRotation="' .. vec(rotation) .. '"'
                .. ' Fov="' .. scalar(camera.fov) .. '" FovType="Yfov" ProjectionType="Perspective"'
                .. ' ZNear="0.1" ZFar="100" ZPositive="false"/>'
            lua[#lua + 1] = '        [' .. quoted(name) .. '] = {'
            lua[#lua + 1] = '            name = ' .. quoted(name) .. ', fov = ' .. scalar(camera.fov)
                .. ', near = 0.1, far = 100,'
            lua[#lua + 1] = '            pos = ' .. luaVec(camera.pos) .. ', look = ' .. luaVec(camera.look)
                .. ', rotation = ' .. luaVec(rotation) .. ','
            lua[#lua + 1] = '        },'
        end
    end
    lua[#lua + 1] = '    },'
    lua[#lua + 1] = '    anchors = {'
    local names = {}
    for name, node in pairs(scene.objects) do
        if not node.error then names[#names + 1] = name end
    end
    table.sort(names)
    for _, name in ipairs(names) do
        assert(not scene.cameras[name], "object name conflicts with an exported camera")
        local point = nativePoint(assert(Projection.anchor(scene, name)))
        xml[#xml + 1] = '  <Node3D Name="' .. xmlEscape(name) .. '" RenderTransformTranslation="' .. vec(point) .. '"/>'
        lua[#lua + 1] = '        [' .. quoted(name) .. '] = ' .. luaVec(point) .. ','
    end
    xml[#xml + 1] = '</Scene>'
    lua[#lua + 1] = '    },'
    lua[#lua + 1] = '}'
    return table.concat(xml, "\n") .. "\n", table.concat(lua, "\n") .. "\n"
end

if ... == "export_workshop_camera" then return Export end
local spec = require "WorkshopInteractions"
if arg and arg[1] then
    spec.source_width = assert(tonumber(arg[1]), "expected source width")
    spec.source_height = assert(tonumber(arg[2]), "expected source height")
    assert(spec.source_width > 0 and spec.source_height > 0, "source dimensions must be positive")
end
local scene = assert(Projection.load(spec.scene_path:gsub("^Book/", "")))
local xml, lua = Export.generate(spec, scene)
local function write(path, contents)
    local file = assert(io.open(path, "w"))
    assert(file:write(contents))
    assert(file:close())
end
write("Scenes/WorkshopCamera.xml", xml)
write("Scripts/WorkshopCamera.lua", lua)
print("Exported Scenes/WorkshopCamera.xml and Scripts/WorkshopCamera.lua")
