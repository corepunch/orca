#!/usr/bin/env python3
"""Build the offline narration and align the recorded speech to the article text."""
import argparse
import io
import re
import subprocess
import tempfile
import wave
from pathlib import Path

from piper import PiperVoice, SynthesisConfig
from pocketsphinx import Decoder


ROOT = Path(__file__).resolve().parents[1]
WORDS = re.compile(r"[A-Za-z]+(?:['’][A-Za-z]+)*")
EXTRA_PRONUNCIATIONS = {
    "octopuses": "AA K T AH P UH S IH Z",
    "octopus's": "AA K T AH P UH S IH Z",
}


def passages(lua):
    script = """
    for _, article in ipairs(dofile(arg[1])) do
        for _, level in ipairs({"first", "more"}) do
            for _, section in ipairs(article[level]) do
                for _, text in ipairs(section) do
                    io.write(article.id, "\\0", level, "\\0", text, "\\0")
                end
            end
        end
    end
    """
    fields = subprocess.check_output(
        [lua, "-", ROOT / "Content/Articles.lua"], input=script.encode()
    ).decode().split("\0")
    tracks = {}
    for index in range(0, len(fields) - 1, 3):
        article, level, text = fields[index:index + 3]
        tracks.setdefault((article, level), []).append(text)
    return tracks


def align(decoder, text, wav_bytes, temp):
    matches = list(WORDS.finditer(text))
    normalized = [word.group().lower().replace("’", "'") for word in matches]
    for word in normalized:
        if not decoder.lookup_word(word):
            if word not in EXTRA_PRONUNCIATIONS:
                raise ValueError(f"Add a pronunciation for {word!r}")
            decoder.add_word(word, EXTRA_PRONUNCIATIONS[word], False)

    source, aligned = temp / "original.wav", temp / "resampled.wav"
    source.write_bytes(wav_bytes)
    aligned.unlink(missing_ok=True)
    subprocess.run(["afconvert", "-f", "WAVE", "-d", "LEI16@16000", source, aligned], check=True)
    with wave.open(str(aligned)) as audio:
        raw = audio.readframes(audio.getnframes())
    decoder.set_align_text(" ".join(normalized))
    decoder.start_utt()
    decoder.process_raw(raw, full_utt=True)
    decoder.end_utt()
    segments = [part for part in decoder.seg() if not part.word.startswith("<")]
    recognized = [re.sub(r"\(\d+\)$", "", part.word) for part in segments]
    if recognized != normalized:
        raise ValueError(f"Could not align {text!r}: {recognized}")
    return [
        (part.start_frame * 10, (part.end_frame + 1) * 10, word.start(), word.end())
        for word, part in zip(matches, segments)
    ]


def lua_string(text):
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'


def generate(model, lua):
    voice = PiperVoice.load(model)
    config = SynthesisConfig(length_scale=1.13, noise_scale=0.0, noise_w_scale=0.0)
    decoder = Decoder(samprate=16000, lm=None, loglevel="ERROR")
    rate = voice.config.sample_rate
    pause_frames = round(rate * 0.28)
    groups = [
        "-- Generated by Tools/generate_narration.py. Do not edit by hand.",
        "return {",
    ]
    staging = tempfile.TemporaryDirectory(prefix="encarta-narration-")
    with staging as directory:
        temp = Path(directory)
        for (article, level), paragraphs in passages(lua).items():
            name = f"{article}-{level}"
            groups.append(f'    ["{name}"] = {{')
            frame = 0
            with wave.open(str(temp / f"{name}.wav"), "wb") as track:
                track.setparams((1, 2, rate, 0, "NONE", "not compressed"))
                for block, text in enumerate(paragraphs, 1):
                    data = io.BytesIO()
                    with wave.open(data, "wb") as audio:
                        voice.synthesize_wav(text, audio, syn_config=config)
                    timings = align(decoder, text, data.getvalue(), temp)
                    groups.append(f"        {{ text = {lua_string(text)}, words = {{")
                    data.seek(0)
                    with wave.open(data, "rb") as audio:
                        base = round(frame * 1000 / rate)
                        duration = round(audio.getnframes() * 1000 / rate)
                        for start, end, left, right in timings:
                            if not 0 <= start < end <= duration + 10:
                                raise ValueError(f"Out-of-range alignment in {name} passage {block}")
                            groups.append(f"            {{ {base + start}, {base + min(end, duration)}, {left}, {right} }},")
                        track.writeframes(audio.readframes(audio.getnframes()))
                        frame += audio.getnframes()
                    groups.append("        } },")
                    track.writeframes(b"\0\0" * pause_frames)
                    frame += pause_frames
            groups.append("    },")
            print(f"{name}: {frame / rate:.1f} s", flush=True)
        groups.append("}")
        for recording in temp.glob("*-*.wav"):
            (ROOT / "Narration" / recording.name).write_bytes(recording.read_bytes())
        (ROOT / "Narration/Timings.lua").write_text("\n".join(groups) + "\n", encoding="utf-8")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("model", type=Path, help="Piper ONNX model with adjacent .onnx.json")
    parser.add_argument("--lua", default="lua", help="Lua executable")
    args = parser.parse_args()
    generate(args.model, args.lua)
